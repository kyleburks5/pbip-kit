"""Keep the GitHub Copilot files in step with the Claude Code ones (work laptops may have Copilot only).

    python tools/copilot/sync.py            write .github/prompts/kit-<command>.prompt.md and .github/copilot-instructions.md
    python tools/copilot/sync.py --check    exit 1 if they differ from what the sources give (tests run this)

Sources (edit these, never the generated files):
- .claude/commands/<name>.md -> .github/prompts/kit-<name>.prompt.md: a Copilot prompt file (front matter
  `name: kit-<name>`, `agent: agent`, a `description` and an `argument-hint`). Run it in Copilot Chat as
  `/kit-<name> <text>`: the `kit-` prefix keeps clear of Copilot's own /plan, /fix and /review. VS Code doesn't fill
  variables in a prompt file's body (`${input:...}` reaches the model as typed; checked in VS Code 1.143.1): the
  text typed after `/<name>` is sent as the chat message, so `$ARGUMENTS` becomes "the text after /<name> in my
  message". `mode:` is the older name of `agent:` (VS Code still reads it as a fallback).
- CLAUDE.md and .claude/rules/*.md -> .github/copilot-instructions.md, in that order, so Copilot reads the same rules.
"""
import argparse, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
NOTE = "Generated by tools/copilot/sync.py from {src}; edit the source and rerun it."
DESCRIPTIONS = {   # what each kit command does (CLAUDE.md "Workflow"); a new command falls back to its first line
    "brd": "Step 0: draft design/reference/brd.md from the template and the brief",
    "model": "Step 1: profile the raw data and propose the core model; 'approved' applies it",
    "plan": "Step 2: tokens, layout.json, spec, audit states and the high-fidelity wireframe",
    "theme": "The colour scheme: brand colours, a reference or a preset, every text and state WCAG AA",
    "build": "Step 3: build the report from layout.json with pbik (no build code), validate and audit",
    "review": "Step 4: screenshot the report, compare with the wireframe and checks, run the numbers audit",
    "fix": "Step 5: fix the review items in layout.json, rebuild, re-check",
    "smoke": "After a tool, plugin or Desktop update: one card, one button slicer, one table",
    "validate": "The numbers audit on its own (look-only)",
    "update": "After a Power BI Desktop update: record it, regression and smoke, Patterns page, harvest, catalog",
}
HINTS = {   # shown in the chat box after /<name>: what to type
    "brd": "the brief: audience, questions, data in data/",
    "model": "nothing to profile and propose, or 'approved' (with any changes) to apply",
    "plan": "design brief, brand colours or a preset (optional)",
    "theme": "brand colours, a reference file, or a preset: clean, bento, corporate",
    "build": "'approved' and any notes from the wireframe review",
    "review": "nothing, or the pages to review",
    "fix": "item IDs from review.md (default: all high and medium)",
    "smoke": "what was updated",
    "validate": "nothing, or the key values to audit",
    "update": "the new Desktop version or release notes",
}


def prompt_file(src):
    text = src.read_text(encoding="utf-8").replace("\r\n", "\n")
    first = text.strip().splitlines()[0] if text.strip() else src.stem
    desc = DESCRIPTIONS.get(src.stem) or re.sub(r"\$ARGUMENTS", "...", first).strip().replace('"', "'")
    desc = desc if len(desc) <= 160 else desc[:157] + "..."
    hint = HINTS.get(src.stem, "optional notes").replace('"', "'")
    body = text.replace("$ARGUMENTS", f"the text after /kit-{src.stem} in my message")
    return (f'---\nname: kit-{src.stem}\nagent: agent\ndescription: "{desc}"\nargument-hint: "{hint}"\n---\n'
            f"<!-- {NOTE.format(src=src.relative_to(ROOT).as_posix())} -->\n"
            f"{body if body.endswith(chr(10)) else body + chr(10)}")


def instructions():
    parts = [f"<!-- {NOTE.format(src='CLAUDE.md and .claude/rules/*.md')} -->\n",
             "Copilot: these are the kit's agent rules, the same ones Claude Code reads. Where they name Claude Code "
             "tools, use the Copilot equivalent:\n\n"
             "- Slash commands (/brd, /plan, ...): the prompts in .github/prompts/, run in Agent mode as /kit-brd, "
             "/kit-plan and so on (Copilot has its own /plan, /fix and /review). The text after the command name is "
             "my input for that step.\n"
             "- The modeling MCP (powerbi-authoring): the tools of Microsoft's Power BI Modeling MCP extension for "
             "VS Code, server `powerbi-authoring-local`. If its tools aren't available, stop and ask me to start it "
             "(MCP: List Servers) and tick its tools (docs/COPILOT.md); never change the model another way. "
             "daxlib-mcp: the server in .mcp.json, or the vendored copy (design/udf/README.md).\n"
             "- Claude Code agents and skills (reports:svg-reviewer, the pbip-validator agent, Data Goblins skills): "
             "not available. Review SVG measures yourself against .claude/rules/svg.md and validate with "
             "`pbik validate`.\n"
             "- Run commands in the terminal from the project root; PowerShell scripts with "
             "`powershell -ExecutionPolicy Bypass -File ...`.\n\n"]
    parts.append((ROOT / "CLAUDE.md").read_text(encoding="utf-8").replace("\r\n", "\n").rstrip() + "\n")
    for f in sorted((ROOT / ".claude" / "rules").glob("*.md")):
        parts.append(f"\n---\n\n# Rules: {f.stem} (.claude/rules/{f.name})\n\n")
        parts.append(f.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip() + "\n")
    return "".join(parts)


def wanted():
    out = {}
    for src in sorted((ROOT / ".claude" / "commands").glob("*.md")):
        out[ROOT / ".github" / "prompts" / f"kit-{src.stem}.prompt.md"] = prompt_file(src)
    out[ROOT / ".github" / "copilot-instructions.md"] = instructions()
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    want = wanted()
    stale = [p for p, t in want.items() if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != t]
    extra = [p for p in (ROOT / ".github" / "prompts").glob("*.prompt.md") if p not in want] \
        if (ROOT / ".github" / "prompts").is_dir() else []
    if a.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT).as_posix()}")
        for p in extra:
            print(f"no source command: {p.relative_to(ROOT).as_posix()}")
        if stale or extra:
            print("run: python tools/copilot/sync.py")
            return 1
        print(f"Copilot files in step ({len(want)} files)")
        return 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(want[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT).as_posix()}")
    for p in extra:
        print(f"note: {p.relative_to(ROOT).as_posix()} has no .claude/commands source (kept; delete it if unused)")
    if not stale:
        print("Copilot files already in step")
    return 0


if __name__ == "__main__":
    sys.exit(main())
